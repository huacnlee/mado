"""Writes lucide.ts: the Lucide icons Mado draws, as typed data.

Usage: python3 -I scripts/lucide.py <icon-nodes.json> [version]

`icon-nodes.json` is lucide-static's `{name: [[tag, attrs], ...]}`. Only the
icons in ICONS are written, so the bundle carries what Mado shows.
"""

import json
import pathlib
import sys

# The icons Mado uses, by Lucide name.
ICONS = [
    "bold", "check", "chevron-down", "clock", "code", "external-link", "eye", "file-code", "file-plus", "file-text", "folder-open", "grip-vertical", "heading", "heading-1", "heading-2", "heading-3", "heading-4", "highlighter", "image", "italic", "link", "list", "list-indent-decrease", "list-indent-increase", "list-ordered", "list-todo", "minus", "pencil", "pilcrow", "plus", "redo-2", "save", "square-code", "strikethrough", "subscript", "superscript", "table", "between-horizontal-start", "between-horizontal-end", "between-vertical-start", "between-vertical-end", "fold-vertical", "fold-horizontal", "grid-2x2-x", "table-cells-merge", "table-cells-split", "panel-top", "text-align-center", "text-align-end", "text-align-justify", "text-align-start", "text-quote", "trash-2", "underline", "undo-2", "unlink", "x", "sun", "moon", "monitor",
]

# The attributes each element's drawing reads.
ATTRS = {
    "path": ["d"],
    "circle": ["cx", "cy", "r"],
    "ellipse": ["cx", "cy", "rx", "ry"],
    "rect": ["x", "y", "width", "height", "rx"],
    "line": ["x1", "y1", "x2", "y2"],
    "polyline": ["points"],
    "polygon": ["points"],
}


def element(tag, attrs):
    out = {"tag": tag}
    for name in ATTRS[tag]:
        if name in attrs:
            value = attrs[name]
            out[name] = value if name in ("d", "points") else float(value)
    return out


def main():
    nodes = json.loads(pathlib.Path(sys.argv[1]).read_text())
    version = sys.argv[2] if len(sys.argv) > 2 else "0.544.0"
    missing = [name for name in ICONS if name not in nodes]
    if missing:
        sys.exit(f"not in Lucide {version}: {', '.join(missing)}")
    lines = [
        f"// Generated by scripts/lucide.py from lucide-static {version}: do not edit.",
        "// Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Contributors.",
        "",
        "/** One element of a Lucide icon, on its 24 × 24 grid. */",
        "export type LucideElement =",
        '  | { tag: "path"; d: string }',
        '  | { tag: "circle"; cx: number; cy: number; r: number }',
        '  | { tag: "ellipse"; cx: number; cy: number; rx: number; ry: number }',
        '  | { tag: "rect"; x: number; y: number; width: number; height: number; rx?: number }',
        '  | { tag: "line"; x1: number; y1: number; x2: number; y2: number }',
        '  | { tag: "polyline" | "polygon"; points: string };',
        "",
        "export const lucide = {",
    ]
    for name in sorted(ICONS):
        elements = [element(tag, attrs) for tag, attrs in nodes[name]]
        lines.append(f"  {json.dumps(name)}: {json.dumps(elements, separators=(', ', ': '))},")
    lines += [
        "} satisfies Record<string, LucideElement[]>;",
        "",
        "/** The name of an icon Mado draws. */",
        "export type LucideName = keyof typeof lucide;",
        "",
    ]
    out = pathlib.Path(__file__).resolve().parent.parent / "examples" / "mado" / "components" / "lucide.ts"
    out.write_text("\n".join(lines))


main()
